-- ── 2 · The parts — home = the tile of the first listed service that is there ─
WITH home AS (
  SELECT DISTINCT ON (l.slot_key) l.slot_key, c.tile_id
    FROM _starter_links l
    JOIN public.canonical_service_taxonomy c ON c.canonical_service = l.canonical_service
    JOIN public.service_categories sc ON sc.id = c.tile_id AND sc.tier = 2
   ORDER BY l.slot_key, l.ord
), base AS (
  SELECT COALESCE(max(sort_order), 0) AS m FROM public.inspiration_parts
), ins AS (
  INSERT INTO public.inspiration_parts (slot_key, label_en, kind, home_category_id, sort_order, hidden, status)
  SELECT p.slot_key, p.label_en, 'part', h.tile_id, base.m + p.ord, FALSE, 'active'
    FROM _starter_parts p
    JOIN home h ON h.slot_key = p.slot_key
   CROSS JOIN base
   ORDER BY p.ord
  ON CONFLICT (slot_key) DO NOTHING
  RETURNING slot_key
)
INSERT INTO _starter_inserted (slot_key) SELECT slot_key FROM ins;

-- ── 3 · The links — ONLY for the parts this run inserted (THE GUARD) ────────
ALTER TABLE public.inspiration_part_services DISABLE TRIGGER inspiration_part_services_keep_categories;

INSERT INTO public.inspiration_part_services (slot_key, canonical_service, sort_order)
SELECT l.slot_key, l.canonical_service,
       (COALESCE((SELECT max(ps.sort_order) FROM public.inspiration_part_services ps WHERE ps.slot_key = l.slot_key), -1)
        + row_number() OVER (PARTITION BY l.slot_key ORDER BY l.ord))::INT
  FROM _starter_links l
  JOIN _starter_inserted i ON i.slot_key = l.slot_key
  JOIN public.canonical_service_taxonomy c ON c.canonical_service = l.canonical_service
ON CONFLICT (slot_key, canonical_service) DO NOTHING;

ALTER TABLE public.inspiration_part_services ENABLE TRIGGER inspiration_part_services_keep_categories;

-- ── 4 · The double write, once, for the new parts only ──────────────────────
INSERT INTO public.inspiration_part_categories (slot_key, category_id, sort_order)
SELECT d.slot_key, d.category_id, d.sort_order
  FROM public.inspiration_part_derived_categories_all() d
  JOIN _starter_inserted i ON i.slot_key = d.slot_key
ON CONFLICT (slot_key, category_id) DO NOTHING;

-- ── Said out loud ───────────────────────────────────────────────────────────
DO $$
DECLARE
  n_parts    INT;
  n_links    INT;
  n_taken    INT;
  n_homeless INT;
  n_missing  INT;
  missing    TEXT;
BEGIN
  SELECT count(*) INTO n_parts FROM _starter_inserted;
  SELECT count(*) INTO n_links
    FROM public.inspiration_part_services ps JOIN _starter_inserted i ON i.slot_key = ps.slot_key;
  SELECT count(*) INTO n_taken FROM _starter_parts p
   WHERE NOT EXISTS (SELECT 1 FROM _starter_inserted i WHERE i.slot_key = p.slot_key)
     AND EXISTS (SELECT 1 FROM public.inspiration_parts x WHERE x.slot_key = p.slot_key);
  SELECT count(*) INTO n_homeless FROM _starter_parts p
   WHERE NOT EXISTS (SELECT 1 FROM public.inspiration_parts x WHERE x.slot_key = p.slot_key);
  SELECT count(DISTINCT l.canonical_service), string_agg(DISTINCT l.canonical_service, ', ')
    INTO n_missing, missing
    FROM _starter_links l
   WHERE NOT EXISTS (SELECT 1 FROM public.canonical_service_taxonomy c WHERE c.canonical_service = l.canonical_service);
  RAISE NOTICE 'starter inspiration parts: % part(s) and % link(s) inserted; % key(s) already existed (left as they are, no links added); % part(s) skipped with no live tier-2 home',
    n_parts, n_links, n_taken, n_homeless;
  IF n_missing > 0 THEN
    RAISE NOTICE 'starter inspiration parts: % service(s) not in canonical_service_taxonomy — their links skipped: %',
      n_missing, missing;
  END IF;
END $$;

