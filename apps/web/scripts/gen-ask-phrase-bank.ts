#!/usr/bin/env tsx
/**
 * gen-ask-phrase-bank.ts — write the ⌘K box's phrase bank (ASK-BRAIN, owner 14 Nov 2026).
 *
 *   pnpm --filter @setnayan/web admin:phrases
 *
 * 🔑 GENERATED, NEVER AUTHORED. Every phrase and its expected first row come from `buildPhraseBank()` — the box's own
 * destinations, the generated job checklist and the keyword table. The committed file is the readable copy;
 * `ask-phrase-bank.test.ts` rebuilds it and fails on any difference, then runs every phrase through the shipped box.
 *
 * WHEN TO RE-RUN: after changing the keyword table, a menu item, or the job checklist (`admin:jobs`).
 */

import { writeFileSync } from 'node:fs';
import { join } from 'node:path';

import { buildPhraseBank } from '../lib/admin-map/ask-phrase-bank';
import { ADMIN_JOBS } from '../lib/admin-map/admin-jobs.generated';
import { ADMIN_ROUTES } from '../lib/admin-map/admin-routes.generated';
import { buildDestinations } from '../app/admin/_components/admin-destinations';

const WEB = join(__dirname, '..');
const OUT = join(WEB, 'lib/admin-map/ask-phrase-bank.generated.ts');

const bank = buildPhraseBank(buildDestinations(), ADMIN_JOBS, ADMIN_ROUTES);
const count = (from: string) => bank.filter((e) => e.from === from).length;

const body = `// AUTO-GENERATED by scripts/gen-ask-phrase-bank.ts — do not hand-edit.
// Regenerate with: pnpm --filter @setnayan/web admin:phrases
//
// The ⌘K box's phrase bank: every phrase and the ONE place its first row must open.
// ${bank.length} phrases — ${count('page')} page names · ${count('job')} job phrasings · ${count('keyword')} keyword-table phrasings · ${count('typo')} misspellings.
// ask-phrase-bank.test.ts fails if this drifts from buildPhraseBank(), and holds the box's accuracy over it.

import { parsePhraseBank } from './ask-phrase-bank';

// One phrase per line: phrase · expected place · source. Read with parsePhraseBank (a text block keeps the type checker
// from expanding 1,600+ object literals into one union type).
export const ASK_PHRASE_BANK = parsePhraseBank(\`
${bank.map((e) => `${e.phrase}\t${e.expect}\t${e.from}`).join('\n')}
\`);
`;

writeFileSync(OUT, body);
console.log(`ask phrase bank: ${bank.length} phrases → ${OUT}`);
