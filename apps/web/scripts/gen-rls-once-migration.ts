/**
 * Generates supabase/migrations/20271281556823_rls_checks_once_per_query.sql
 * from the replayed schema — every public policy whose predicate `askOnce`
 * would change, and nothing else.
 *
 *   pnpm --filter @setnayan/web exec tsx scripts/gen-rls-once-migration.ts
 *
 * REGENERATE, never hand-edit, if `main` moves a policy before this merges:
 * the per-policy guard in the file skips (with a NOTICE) any policy whose
 * text no longer matches what it was generated from, so a stale file is
 * slow, never wrong — but a regenerated one is fast again. The proof is
 * tests/db/rls-checks-once-per-query.db.test.ts.
 *
 * It also prints the Supabase advisor counts this schema would score before
 * and after (auth_rls_initplan is a text rule; replicated in `initplanFlag`).
 */
import fs from 'node:fs';
import path from 'node:path';
import { createReplayedDb, MIGRATIONS_DIR, versionOf } from '../tests/db/replay-migrations';
import { askOnce, moderatorCallsAreMonotone } from '../tests/db/policy-asks-once';

export const MIGRATION_FILE = '20271281556823_rls_checks_once_per_query.sql';

type Pol = {
  tablename: string;
  policyname: string;
  cmd: string;
  qual: string | null;
  with_check: string | null;
};

/** Supabase lint 0003 auth_rls_initplan, as text — one finding per policy. */
export function initplanFlag(p: { qual: string | null; with_check: string | null }): boolean {
  const hit = (e: string | null) =>
    e !== null &&
    (['uid', 'jwt', 'role', 'email'].some(
      (f) => e.includes(`auth.${f}()`) && !e.toLowerCase().includes(`select auth.${f}()`),
    ) ||
      (/current_setting\(.*\)/.test(e) && !/select current_setting\(.*\)/.test(e.toLowerCase())));
  return hit(p.qual) || hit(p.with_check);
}

const lit = (s: string) => `'${s.replace(/'/g, "''")}'`;
const ident = (s: string) => `"${s.replace(/"/g, '""')}"`;

const HEADER = `-- ════════════════════════════════════════════════════════════════════════════
-- RLS CHECKS ONCE PER QUERY, NOT ONCE PER ROW — same rows, same people.
--
-- GENERATED by apps/web/scripts/gen-rls-once-migration.ts from the replayed
-- schema. Regenerate it; do not hand-edit it. The rewrite itself, and why each
-- part of it admits exactly the rows it admitted before, is documented in
-- apps/web/tests/db/policy-asks-once.ts (askOnce). The proof is
-- apps/web/tests/db/rls-checks-once-per-query.db.test.ts: an identity matrix
-- (host, co-host, helper, delegates, coordinator, guest with a pass, linked and
-- unlinked supplier, stranger, admin, anon) x SELECT / INSERT / UPDATE / DELETE
-- on every policy table this touches, run on the SAME seeded database before
-- and after this file, must match byte for byte.
--
-- WHY (owner, 2026-10-20: "we want all pages to load at its fastest").
-- Measured on prod, read-only: one guests query cost 21-27 ms mean with the
-- user's JWT against 1.5 ms as service_role. Supabase's performance advisor
-- reported 275 auth_rls_initplan findings — auth.uid() & co. re-evaluated for
-- every row. Three things are re-evaluated per row, and each is fixed here
-- without touching who a policy admits:
--   1. auth.uid() / auth.jwt() / auth.role() / auth.email()   → (SELECT auth.uid())
--   2. is_admin() / is_console_admin()                         → (SELECT is_admin())
--   3. moderator_area_level(event_id, '<area>') <P>            → event_id IN (one set)
--      via current_moderator_area_levels(area), created below.
-- Only ALTER POLICY ... USING / WITH CHECK: no policy is dropped, created,
-- renamed, re-roled, or moved between PERMISSIVE and RESTRICTIVE.
--
-- Each ALTER runs only if that policy still reads exactly as it did when this
-- file was generated (md5 of qual|with_check). A policy changed by a migration
-- that landed in between is LEFT AS IT IS, with a NOTICE — slower, never wrong,
-- and never a stalled deploy.
--
-- NOT DONE HERE, deliberately: merging permissive policies (Supabase's
-- multiple_permissive_policies). Postgres already ORs every permissive policy
-- for a role+command into one qual, so a merge changes no plan and no
-- timing — and on guests/orders the overlap is with FOR ALL policies, which a
-- same-command merge cannot remove anyway. See the PR body for the measurement.
-- ════════════════════════════════════════════════════════════════════════════

-- The set form of moderator_area_level(): every event this caller holds a
-- live helper seat on, with the level moderator_area_level() itself resolves
-- for that area. event_moderators is UNIQUE (event_id, user_id), so each event
-- appears once and the resolver's LIMIT 1 is deterministic. Policies test
-- "event_id IN (this, filtered by level)" — one call per statement — where
-- they used to call the resolver once per row.
CREATE OR REPLACE FUNCTION public.current_moderator_area_levels(p_area text)
RETURNS TABLE (event_id uuid, level text)
LANGUAGE sql STABLE SECURITY DEFINER
SET search_path = public
AS $$
  SELECT m.event_id, public.moderator_area_level(m.event_id, p_area)
    FROM public.event_moderators m
   WHERE m.user_id = auth.uid()
     AND m.accepted_at IS NOT NULL
     AND m.removed_at IS NULL;
$$;
REVOKE ALL ON FUNCTION public.current_moderator_area_levels(text) FROM PUBLIC, anon;
GRANT EXECUTE ON FUNCTION public.current_moderator_area_levels(text) TO authenticated;
`;

async function main(): Promise<void> {
  const mine = versionOf(MIGRATION_FILE);
  const only = new Set(
    fs
      .readdirSync(MIGRATIONS_DIR)
      .filter((f) => f.endsWith('.sql'))
      .map(versionOf)
      .filter((v) => v < mine),
  );
  const r = await createReplayedDb({ only });
  const pols = (
    await r.db.query<Pol>(
      `SELECT tablename, policyname, cmd, qual, with_check
         FROM pg_policies WHERE schemaname = 'public'
        ORDER BY tablename, policyname`,
    )
  ).rows;
  await r.db.close();

  const blocks: string[] = [];
  const tables = new Set<string>();
  let before = 0;
  let after = 0;
  const counts = { auth: 0, helper: 0, moderator: 0 };
  for (const p of pols) {
    if (initplanFlag(p)) before++;
    const nq = askOnce(p.qual);
    const nc = askOnce(p.with_check);
    if (initplanFlag({ qual: nq, with_check: nc })) after++;
    if (nq === p.qual && nc === p.with_check) continue;

    for (const e of [p.qual, p.with_check]) {
      const bad = moderatorCallsAreMonotone(e);
      if (bad.length) throw new Error(`${p.tablename}.${p.policyname}: ${bad.join('; ')}`);
    }
    const both = `${p.qual ?? ''} ${p.with_check ?? ''}`;
    if (/(?<!SELECT )auth\.\w+\(\)/.test(both)) counts.auth++;
    if (/(?<![\w.])(?<!SELECT )is_(console_)?admin\(\)/.test(both)) counts.helper++;
    if (both.includes('moderator_area_level(')) counts.moderator++;

    const md5 = (
      await import('node:crypto')
    ).createHash('md5').update(`${p.qual ?? '~'}|${p.with_check ?? '~'}`).digest('hex');
    const clauses: string[] = [];
    if (nq !== p.qual) clauses.push(`USING (${nq})`);
    if (nc !== p.with_check) clauses.push(`WITH CHECK (${nc})`);
    const body = `ALTER POLICY ${ident(p.policyname)} ON public.${ident(p.tablename)}\n    ${clauses.join('\n    ')};`;
    if (body.includes('$rls$')) throw new Error('dollar tag collision');
    tables.add(p.tablename);
    blocks.push(
      `DO $rls$ BEGIN\n` +
        `  IF (SELECT md5(coalesce(qual, '~') || '|' || coalesce(with_check, '~')) FROM pg_policies\n` +
        `       WHERE schemaname = 'public' AND tablename = ${lit(p.tablename)} AND policyname = ${lit(p.policyname)})\n` +
        `     = '${md5}' THEN\n` +
        `    ${body}\n` +
        `  ELSE\n` +
        `    RAISE NOTICE 'rls-once: public.% policy % changed since generation; left as it is', ${lit(p.tablename)}, ${lit(p.policyname)};\n` +
        `  END IF;\n` +
        `END $rls$;\n`,
    );
  }

  const out = `${HEADER}
-- ${blocks.length} policies on ${tables.size} tables:
--   ${counts.auth} wrap auth.*() · ${counts.helper} wrap is_admin()/is_console_admin() · ${counts.moderator} use the moderator set
-- auth_rls_initplan (advisor rule, replayed schema): ${before} → ${after}

${blocks.join('\n')}`;
  fs.writeFileSync(path.join(MIGRATIONS_DIR, MIGRATION_FILE), out);
  console.log(
    JSON.stringify({ policies: blocks.length, tables: tables.size, ...counts, initplanBefore: before, initplanAfter: after }),
  );
}

if (process.argv[1] && process.argv[1].endsWith('gen-rls-once-migration.ts')) {
  void main().catch((e) => {
    console.error(e);
    process.exit(1);
  });
}
