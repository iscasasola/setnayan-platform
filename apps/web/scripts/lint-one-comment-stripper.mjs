#!/usr/bin/env node
/**
 * lint-one-comment-stripper.mjs
 *
 * There is ONE comment stripper in this repo — `apps/web/lib/strip-comments.ts`
 * (and its byte-identical JS twin in `scripts/port-controls.mjs`). This guard
 * stops a second one being written, and turns the ones that already exist into
 * a debt that can only be paid down.
 *
 * ── WHY A GUARD AND NOT A NOTE ──────────────────────────────────────────────
 * Roughly half the guards in this repo work by reading source text and matching
 * a pattern, so every one needs the same first step: remove comments, so that
 * PROSE ABOUT a banned construct is not mistaken for the construct. The obvious
 * two-line way to do that is wrong:
 *
 *     src.replace(<block comments>, '').replace(<line comments>, '')
 *
 * It strips BLOCK comments FIRST, so a `//` line comment containing a block
 * opener — `content-type video/*`, and this codebase writes that constantly —
 * opens a comment that never existed, which then closes at the next real `*​/`
 * and takes every line between with it.
 *
 * 🚨 AND IT IS SILENT IN THE DIRECTION THAT MATTERS. On 2026-08-30 adding ONE
 * JSDoc block to `app/api/papic/guest-capture/route.ts` turned six unrelated
 * guards red at once, because that file already held such a line comment and
 * the JSDoc finally gave the stray opener something to close at: the text those
 * guards could see fell from 16,218 characters to 6,430. That was the LOUD
 * direction, and it was luck. The same mechanism makes a guard pass while
 * asserting against a blank, and nothing anywhere would say so.
 *
 * ── HOW IT DECIDES ──────────────────────────────────────────────────────────
 * It strips comments with the REAL stripper before looking, so a docblock
 * describing the hazard (like this one) is not itself a finding.
 *
 * ── THE BASELINE IS A DEBT, AND IT MAY ONLY SHRINK ──────────────────────────
 * 301 files already carry a private copy. Rewriting them is a programme, not a
 * commit: they hold 205 distinct shapes, and changing what a guard SEES changes
 * what it asserts, so each one needs its own judgement. So they are listed, and
 * the list is enforced in both directions — a NEW file fails, and a file that
 * has been migrated must be REMOVED from the list, which is what stops it
 * rotting into a page nobody reads.
 */
import { readFileSync, readdirSync, statSync, writeFileSync } from 'node:fs';
import { join, dirname, relative } from 'node:path';
import { fileURLToPath } from 'node:url';
import { stripComments } from './port-controls.mjs';

const WEB = join(dirname(fileURLToPath(import.meta.url)), '..');
const ROOT = join(WEB, '..', '..');
const BASELINE = join(WEB, 'scripts', 'one-comment-stripper.baseline.txt');

/** The signatures of a hand-rolled stripper, as literal substrings. */
const SIGNATURES = [
  String.raw`/\/\*[\s\S]*?\*\//g`,
  String.raw`/\{\/\*[\s\S]*?\*\/\}/g`,
  String.raw`/\{\s*\/\*[\s\S]*?\*\/\s*\}/g`,
  String.raw`/^\s*\/\/.*$/gm`,
  String.raw`/\/\/.*$/gm`,
  String.raw`/(^|[^:])\/\/[^\n]*/g`,
];

/** The two files that are ALLOWED to contain the naive pattern in code: the
 *  real stripper's own tests compare against it, and the guard you are reading
 *  has to name what it is looking for. */
const ALLOWED = new Set([
  'apps/web/lib/strip-comments.test.ts',
  'apps/web/scripts/lint-one-comment-stripper.mjs',
]);

const walk = (dir, out = []) => {
  let entries;
  try {
    entries = readdirSync(dir);
  } catch {
    return out;
  }
  for (const name of entries) {
    if (name === 'node_modules' || name === '.next' || name === '.git') continue;
    const p = join(dir, name);
    if (statSync(p).isDirectory()) walk(p, out);
    else if (/\.(ts|tsx|mjs|js)$/.test(name)) out.push(p);
  }
  return out;
};

const found = [];
for (const p of ['apps/web/lib', 'apps/web/app', 'apps/web/tests', 'apps/web/components', 'apps/web/scripts', 'scripts'].flatMap(
  (r) => walk(join(ROOT, r)),
)) {
  const rel = relative(ROOT, p);
  if (ALLOWED.has(rel)) continue;
  // 🔑 Strip with the REAL stripper first, so prose about the hazard is not a
  // finding. This guard eats its own cooking.
  const code = stripComments(readFileSync(p, 'utf8'));
  if (SIGNATURES.some((s) => code.includes(s))) found.push(rel);
}
found.sort();

if (process.argv.includes('--write')) {
  const header = [
    '# Files carrying their own comment stripper instead of lib/strip-comments.ts.',
    '#',
    '# A DEBT, NOT A DECISION. Generated by scripts/lint-one-comment-stripper.mjs',
    '# --write. This list may only SHRINK: a new entry fails the build, and an',
    '# entry whose file has been migrated must be deleted here in the same change.',
    '#',
    `# ${found.length} files at the time of writing.`,
    '',
  ].join('\n');
  writeFileSync(BASELINE, header + found.join('\n') + '\n');
  console.log(`wrote ${BASELINE} — ${found.length} files`);
  process.exit(0);
}

const baseline = readFileSync(BASELINE, 'utf8')
  .split('\n')
  .map((l) => l.trim())
  .filter((l) => l.length > 0 && !l.startsWith('#'));
const known = new Set(baseline);

const added = found.filter((f) => !known.has(f));
const paid = baseline.filter((f) => !found.includes(f));

if (added.length === 0 && paid.length === 0) {
  console.log(
    `✓ lint-one-comment-stripper: no NEW private comment stripper (${found.length} known, unchanged)`,
  );
  process.exit(0);
}

if (added.length > 0) {
  console.error(
    `✗ ${added.length} file(s) grew their own comment stripper.\n` +
      '  Use `stripComments` from lib/strip-comments.ts (or scripts/port-controls.mjs\n' +
      '  under plain node). A two-replace regex strips BLOCK comments first, so a\n' +
      '  line comment containing `video/*` opens a comment that closes at the next\n' +
      '  real `*' + '/` and blanks everything between — and the guard then asserts\n' +
      '  against a blank and passes.\n',
  );
  for (const f of added) console.error(`  ${f}`);
  console.error('');
}

if (paid.length > 0) {
  console.error(
    `✗ ${paid.length} baseline entr(y/ies) no longer carry one — delete them from\n` +
      `  ${relative(ROOT, BASELINE)} in this same change. A baseline that keeps stale\n` +
      '  lines is a page nobody reads, and the next real finding hides in it.\n',
  );
  for (const f of paid) console.error(`  ${f}`);
}
process.exit(1);
