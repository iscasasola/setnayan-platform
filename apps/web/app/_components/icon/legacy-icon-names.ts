/** A name a row may store. */
export type StoredIconName = keyof typeof LEGACY_ICON_NAMES;

/** The glyph a stored (lucide) name draws, or null when it is not on the list. */
export function glyphForStoredName(name: string | null | undefined): IconComponent | null {
  if (!name || !Object.prototype.hasOwnProperty.call(LEGACY_ICON_NAMES, name)) return null;
  return GLYPHS[LEGACY_ICON_NAMES[name as StoredIconName]];
}
