#!/usr/bin/env node
/**
 * GENERATE the papic_challenge_library seed from `apps/web/lib/papic-challenge-pool.ts`.
 *
 * 🔑 A GUARD COMPARING TWO HAND-TYPED THINGS IS NOT A GUARD. Six hundred rows
 * cannot be kept in step with a migration by care alone — `llms.txt` drifted
 * for three weeks with green CI doing exactly that. So the pool is authored
 * ONCE, in TypeScript, and this script prints the SQL. Nothing is typed twice.
 *
 *   node scripts/emit-papic-challenge-pool.mjs            # print the rows
 *   node scripts/emit-papic-challenge-pool.mjs --check <migration.sql>
 *
 * `--check` re-emits and compares against the committed migration. It is wired
 * into CI, so editing the pool without regenerating fails the build instead of
 * shipping a database that disagrees with the screen reading from it.
 *
 * ⚠ THE INSERT IS AN UPSERT, ON PURPOSE. Sixty of these rows are already in
 * production. A plain INSERT would abort the whole migration on the first of
 * them; `ON CONFLICT (library_id) DO UPDATE` re-states the row instead, which
 * is also how a wording fix reaches the table later.
 */
import { readFileSync } from 'node:fs';
import { pathToFileURL } from 'node:url';
import { resolve, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const repoRoot = resolve(here, '..');

/** Postgres string literal. Doubling the quote is the only escape SQL has. */
function lit(v) {
  if (v === null || v === undefined) return 'NULL';
  return `'${String(v).replace(/'/g, "''")}'`;
}

/** text[] literal, or NULL for "fits any event type". */
function arr(v) {
  if (v === null || v === undefined) return 'NULL';
  return `ARRAY[${v.map(lit).join(', ')}]::text[]`;
}

export async function emit() {
  // tsx registers the TS loader; this file is .mjs so it can be run either way.
  const mod = await import(
    pathToFileURL(resolve(repoRoot, 'apps/web/lib/papic-challenge-pool.ts')).href
  );
  const pool = mod.CHALLENGE_POOL;

  const values = pool
    .map(
      (r) =>
        `  (${r.libraryId}, ${lit(r.slug)}, ${lit(r.category)}, ${lit(r.title)}, ` +
        `${lit(r.prompt)}, ${lit(r.captureKind)}, ${lit(r.missionType)}, ` +
        `${r.priorityRank === null ? 'NULL' : r.priorityRank}, ${arr(r.eventTypes)})`,
    )
    .join(',\n');

  return `-- GENERATED by scripts/emit-papic-challenge-pool.mjs — DO NOT EDIT BY HAND.
-- Source of truth: apps/web/lib/papic-challenge-pool.ts (${pool.length} challenges).
INSERT INTO public.papic_challenge_library
  (library_id, slug, category, title, prompt, capture_kind, mission_type, priority_rank, event_types)
VALUES
${values}
ON CONFLICT (library_id) DO UPDATE SET
  slug          = EXCLUDED.slug,
  category      = EXCLUDED.category,
  title         = EXCLUDED.title,
  prompt        = EXCLUDED.prompt,
  capture_kind  = EXCLUDED.capture_kind,
  mission_type  = EXCLUDED.mission_type,
  priority_rank = EXCLUDED.priority_rank,
  event_types   = EXCLUDED.event_types;
`;
}

const isMain = process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href;
if (isMain) {
  const sql = await emit();
  const checkIdx = process.argv.indexOf('--check');
  if (checkIdx === -1) {
    process.stdout.write(sql);
  } else {
    const target = process.argv[checkIdx + 1];
    if (!target) {
      console.error('--check needs a migration path');
      process.exit(2);
    }
    const committed = readFileSync(resolve(repoRoot, target), 'utf8');
    // The migration carries DDL above the generated block; compare the block.
    if (!committed.includes(sql.trim())) {
      console.error(
        `✗ ${target} does not contain the current generated pool.\n` +
          `  Regenerate it: node scripts/emit-papic-challenge-pool.mjs`,
      );
      process.exit(1);
    }
    console.log(`✓ ${target} matches the pool (${(sql.match(/\n  \(/g) || []).length} rows)`);
  }
}
