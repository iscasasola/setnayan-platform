/**
 * design-rules-findings.ts — what the 2026-10-28 rules find in the tree today, in one shape, so the guard
 * (`lib/every-back-goes-home.test.ts`) and the baseline generator (`scripts/gen-design-rules-baseline.ts`)
 * can never disagree about what they are counting. Filesystem-bound (see design-rules-scan.ts).
 */
import { join } from 'node:path';

import { HOMES, IN_PAGE_BACKS, RETIRED_PAGES, pageHome } from '@/lib/page-home';
import {
  WEB,
  appTsxFiles,
  backLinksIn,
  designCountsIn,
  homePath,
  hrefMatchesHome,
  isRedirectStub,
  listPages,
  normaliseHref,
  pageScope,
  type BackLink,
} from '@/lib/design-rules-scan';

export const BASELINE_PATH = join(WEB, 'lib/design-rules.baseline.json');

export type Baseline = {
  _: string;
  /** `file | href → expected` — back links that disagree with the map today. Ratchets DOWN. */
  wrongBacks: string[];
  /** file → its ad-hoc back links (not `BackButton`). Ratchets DOWN. */
  adHocBacks: Record<string, number>;
  /** file → raw hex colours. Never UP. */
  hex: Record<string, number>;
  /** file → raw Tailwind palette colours. Never UP. */
  palette: Record<string, number>;
  /** file → raw `<select>`. Never UP. */
  select: Record<string, number>;
};

export type BackFinding = { route: string; link: BackLink; key: string; why: string };

/** Map problems: a page whose home is not a live page, or a `HOMES` key that matches no page. */
export function mapProblems(): string[] {
  const pages = listPages();
  const live = new Map(pages.map((p) => [p.route, p.file]));
  const stubs = new Set(pages.filter((p) => isRedirectStub(p.file)).map((p) => p.route));
  const out: string[] = [];
  for (const p of pages) {
    if (stubs.has(p.route)) continue; // a redirect stub draws nothing, so it has no back
    const h = pageHome(p.route);
    if (h.kind === 'none') continue;
    const path = homePath(h.home);
    if (!live.has(path)) out.push(`${p.route} → ${h.home}: no such page`);
    else if (stubs.has(path)) out.push(`${p.route} → ${h.home}: a redirect stub, not a home`);
    else if (path in RETIRED_PAGES) out.push(`${p.route} → ${h.home}: retired (${RETIRED_PAGES[path]})`);
  }
  const routes = pages.map((p) => p.route);
  for (const key of Object.keys(HOMES)) {
    const re = new RegExp(
      `^${key
        .replace(/[.*+?^${}()|[\]\\]/g, (c) => (c === '*' ? '*' : `\\${c}`))
        .replace(/\/\*\*$/, '(?:/[^/]+)+')
        .replace(/\/\*$/, '/[^/]+')}$`,
    );
    if (!routes.some((r) => re.test(r))) out.push(`HOMES['${key}'] matches no page on disk — stale entry`);
  }
  return out;
}

/** Every back link on every page that disagrees with the map. */
export function backFindings(): BackFinding[] {
  const out: BackFinding[] = [];
  const seen = new Set<string>();
  for (const p of listPages()) {
    if (isRedirectStub(p.file)) continue;
    const h = pageHome(p.route);
    for (const rel of pageScope(p.file)) {
      for (const link of backLinksIn(rel)) {
        let why: string | null = null;
        if (link.prop === 'route') {
          if (link.href !== p.route) why = `BackButton route="${link.href}" is not this page (${p.route})`;
        } else if (h.kind === 'none') {
          if (h.reason !== 'lab' && h.reason !== 'computed') why = `the map says no back here (${h.reason})`;
        } else if (normaliseHref(link.href) === normaliseHref(p.route) && p.route in IN_PAGE_BACKS) {
          why = null;
        } else if (!hrefMatchesHome(link.href, h.home)) {
          why = `expected ${h.home}`;
        }
        if (!why) continue;
        const key = `${rel} | ${link.href} → ${why}`;
        if (seen.has(key)) continue;
        seen.add(key);
        out.push({ route: p.route, link, key, why });
      }
    }
  }
  return out.sort((a, b) => (a.key < b.key ? -1 : 1));
}

/** file → number of ad-hoc back links, over every page's scope. */
export function adHocCounts(): Record<string, number> {
  const out: Record<string, number> = {};
  const files = new Set(listPages().flatMap((p) => pageScope(p.file)));
  for (const rel of [...files].sort()) {
    const n = backLinksIn(rel).filter((l) => l.kind === 'ad-hoc').length;
    if (n) out[rel] = n;
  }
  return out;
}

/** file → raw hex / palette / select counts, every app .tsx, non-zero only. */
export function designCounts(): Pick<Baseline, 'hex' | 'palette' | 'select'> {
  const hex: Record<string, number> = {};
  const palette: Record<string, number> = {};
  const select: Record<string, number> = {};
  for (const rel of appTsxFiles()) {
    const c = designCountsIn(rel);
    if (c.hex) hex[rel] = c.hex;
    if (c.palette) palette[rel] = c.palette;
    if (c.select) select[rel] = c.select;
  }
  return { hex, palette, select };
}

export const BASELINE_NOTE =
  'GENERATED by `pnpm --filter @setnayan/web design-rules:baseline --write` (scripts/gen-design-rules-baseline.ts) — never hand-edit. A RATCHET (lib/every-back-goes-home.test.ts): a new entry or a higher count fails; a removed wrongBack / adHocBack must be dropped by regenerating. Regenerating to turn a red run green is not the fix — use BackButton route=, a colour token, PickMenu.';

export function currentBaseline(): Baseline {
  return {
    _: BASELINE_NOTE,
    wrongBacks: backFindings().map((f) => f.key),
    adHocBacks: adHocCounts(),
    ...designCounts(),
  };
}
