/**
 * every-stage-is-todays-page.test.ts — WITH NOTHING STORED PER STAGE, EVERY STAGE'S GUEST PAGE IS THE PAGE IT WAS.
 *
 * "WHAT GUESTS SEE" (DECISION_LOG 2026-10-10) gives a couple one value per scene PER STAGE. Its first rule is that a
 * couple who has stored nothing sees no change at all — on any stage, for any reader. This file is that rule, held on
 * the REAL guest page (`SiteBody`, drawn by `lib/site-body-fixture-render.ts` with no database — read that file's
 * docblock for the seam and for what a render is not).
 *
 * HOW IT WAS MADE — RECORD FIRST, THEN BUILD. `every-stage-is-todays-page.golden.json` was written on untouched
 * `origin/main` (a316051dd), in a commit that touches no page file, BEFORE the per-stage value existed. Every case in
 * `lib/stage-pages-fixture.ts` (4 stages × a listed guest and a reader with no key × the scenes all on · some switched
 * off by today's eye · open browsing, and the Save the Date led by its film and by the photos) is one page; the record keeps its length and
 * its SHA-256. The build that follows must leave every one of them identical.
 *
 * A hash says "changed", not where. When a case goes red: check out the commit before your change, run
 * `STAGE_PAGES_DUMP=<dir> ../../node_modules/.bin/tsx --test lib/every-stage-is-todays-page.test.ts` there and on your
 * branch, and diff the two folders — each case is written as one HTML file.
 *
 * After an INTENDED change to what a guest page draws with nothing stored: `UPDATE_GOLDEN=1` on the same command,
 * and say in the commit which cases moved and why. `lib/site-body-fixture.golden.html` (the Invitation, in full) is a
 * separate record and is not regenerated by this.
 *
 *   (1) the record is not an empty shell: each stage's page carries what that stage is known to draw today;
 *   (2) every case is the recorded page, byte for byte.
 */
import { test } from 'node:test';
import assert from 'node:assert/strict';
import { createHash } from 'node:crypto';
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
/* FIRST: this import brings in the renderer, which installs its seam before anything draws the guest page. */
import { STAGE_CASES, STAGE_WORDS, caseName, renderStagePage, type StageCase } from './stage-pages-fixture';
import { FIXTURE_BLOCKS, FIXTURE_WORDS } from './site-body-fixture';

const GOLDEN = join(__dirname, 'every-stage-is-todays-page.golden.json');
type Record_ = Record<string, { bytes: number; sha256: string }>;

const sha = (s: string) => createHash('sha256').update(s).digest('hex');
const fileOf = (c: StageCase) => `${c.stage}.${c.reader}.${c.arrangement}.html`;

const pages = new Map<string, string>();
async function page(c: StageCase): Promise<string> {
  const key = caseName(c);
  if (!pages.has(key)) {
    const drawn = await renderStagePage(c);
    assert.deepEqual(drawn.complaints, [], `React or the page complained while drawing ${key}`);
    pages.set(key, drawn.html);
    const dump = process.env.STAGE_PAGES_DUMP;
    if (dump) {
      mkdirSync(dump, { recursive: true });
      writeFileSync(join(dump, fileOf(c)), drawn.html);
    }
  }
  return pages.get(key)!;
}

const of = (stage: StageCase['stage'], reader: StageCase['reader'], arrangement: StageCase['arrangement'] = 'plain') =>
  page(STAGE_CASES.find((c) => c.stage === stage && c.reader === reader && c.arrangement === arrangement)!);

test('(1) the record is real pages: each stage draws what it is known to draw today, and the eye’s gaps are on the record', async () => {
  assert.equal(STAGE_CASES.length, 28);
  assert.equal(new Set(STAGE_CASES.map(caseName)).size, STAGE_CASES.length, 'two cases share a name');

  /* The Invitation, a listed guest: the scenes of its list, the guest's own reply sheet. */
  const invite = await of('rsvp', 'guest');
  assert.ok(invite.length > 20_000, `the Invitation is ${invite.length} bytes`);
  assert.ok(invite.includes(FIXTURE_WORDS.message) && invite.includes(FIXTURE_WORDS.dressTitle) && invite.includes(STAGE_WORDS.reminder));
  assert.ok(invite.includes(STAGE_WORDS.howWeMet), 'the love story scene');
  assert.ok(!invite.includes(STAGE_WORDS.proseOpening), 'with the scene on the page the prose does not stand in');
  assert.ok(invite.includes('id="rsvp-sheet-heading"'));
  assert.ok(invite.includes(STAGE_WORDS.ownSceneTitle), 'the couple’s own scene');

  /* The Save the Date holds the date: no dress code, no reminders, no run of show. Led by the photos, it draws the
     gallery scene and the love story scene; led by the film, the gallery is the film's own. */
  const std = await of('save_the_date', 'guest', 'photos');
  assert.ok(std.includes(STAGE_WORDS.howWeMet) && std.includes(STAGE_WORDS.photo), 'its love story and its photos');
  assert.ok(!std.includes(FIXTURE_WORDS.dressTitle) && !std.includes(STAGE_WORDS.reminder));
  const film = await of('save_the_date', 'guest', 'film');
  assert.ok(film.includes(STAGE_WORDS.photo), 'the film carries the gallery itself');
  assert.notEqual(film, std);
  /* …and with the film switched off by the link, its plain stand-in draws a love story of its OWN above the scene. */
  const noFilm = await of('save_the_date', 'guest');
  assert.equal(noFilm.split(STAGE_WORDS.howWeMet).length - 1, 2, 'the stand-in’s love story and the scene’s');

  /* 🧭 THE DAY: the dress code and the reminders are NOT in the day's list, and a guest still meets the reminders
     (the Day's Welcome) — and the love story's PROSE, because the day's list has no love story scene to stand for it. */
  const day = await of('event', 'guest');
  for (const b of FIXTURE_BLOCKS) assert.ok(day.includes(b.label.replace('&', '&amp;')), `the day’s run of show: ${b.label}`);
  assert.ok(day.includes(STAGE_WORDS.reminder), 'the Day’s Welcome carries the reminders');
  assert.ok(day.includes(STAGE_WORDS.proseOpening), 'the prose love story is drawn on the day');
  assert.ok(!day.includes(FIXTURE_WORDS.message), 'the note is not the day’s');

  /* Post Event: the story, the photos, the note — no dress code, no countdown. */
  const after = await of('editorial', 'guest');
  assert.ok(after.includes(STAGE_WORDS.howWeMet) && after.includes(FIXTURE_WORDS.message));
  assert.ok(!after.includes(FIXTURE_WORDS.dressTitle) && !after.includes(STAGE_WORDS.reminder));

  /* 👁 TODAY'S EYE, AS IT STANDS (the `hidden` arrangement switches five scenes off for the whole event): */
  const inviteHidden = await of('rsvp', 'guest', 'hidden');
  assert.ok(!inviteHidden.includes(FIXTURE_WORDS.dressTitle) && !inviteHidden.includes(STAGE_WORDS.reminder), 'the list follows the eye');
  assert.ok(inviteHidden.includes(STAGE_WORDS.proseOpening), 'a hidden love story scene falls back to the prose (today’s behaviour, kept)');
  const dayHidden = await of('event', 'guest', 'hidden');
  assert.ok(!dayHidden.includes(STAGE_WORDS.reminder), 'the Day’s Welcome follows the eye');
  assert.ok(dayHidden.includes(FIXTURE_BLOCKS[1]!.label), 'the Day’s own schedule block does NOT follow the eye (today’s behaviour, kept)');

  /* A reader with no key gets the stranger’s page, never the guest’s. */
  const stranger = await of('rsvp', 'anonymous');
  assert.ok(!stranger.includes('id="rsvp-sheet-heading"') && !stranger.includes(FIXTURE_WORDS.guestFirst));
});

test('(2) byte for byte: every stage, for both readers, in every arrangement, is the recorded page', async () => {
  const now: Record_ = {};
  for (const c of STAGE_CASES) {
    const html = await page(c);
    now[caseName(c)] = { bytes: Buffer.byteLength(html), sha256: sha(html) };
  }
  if (process.env.UPDATE_GOLDEN === '1') {
    writeFileSync(GOLDEN, `${JSON.stringify(now, null, 2)}\n`);
    return;
  }
  assert.ok(existsSync(GOLDEN), 'the record is missing — it is only ever written with UPDATE_GOLDEN=1');
  const then = JSON.parse(readFileSync(GOLDEN, 'utf8')) as Record_;
  assert.deepEqual(Object.keys(now).sort(), Object.keys(then).sort(), 'the cases and the record do not name the same pages');
  const moved = Object.keys(now).filter((k) => now[k]!.sha256 !== then[k]!.sha256);
  assert.deepEqual(
    moved.map((k) => `${k}: ${then[k]!.bytes} → ${now[k]!.bytes} bytes`),
    [],
    'a guest page changed with nothing stored per stage (STAGE_PAGES_DUMP=<dir> on both commits, then diff the folders)',
  );
});
